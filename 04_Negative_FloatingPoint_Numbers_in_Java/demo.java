
public class demo {

    public static void main(String[] args) {
        float f = 1.125f;
        System.out.println(f); // output = 1.125
        System.out.printf("%.10f%n", f); // output = 1.1250000000

        float f1 = 0.7f;
        System.out.println(f1); // output = 0.7
        System.out.printf("%.10f%n", f1); // output = 0.6999999881
    }
}
 